/* All Documents (+ empty state), Document Categories and Upload / Edit Document. */
(function () {
  'use strict';
  var A = window.PSUAdmin, U = PSU.util, esc = A.esc;
  var PER_PAGE = 8;

  function catName(id) {
    var c = PSU.db.get('categories', id);
    return c ? c.name : 'Uncategorized';
  }

  /* Mock file: the prototype keeps document details only, so downloads/views produce a small sample file. */
  PSUAdmin.sampleFile = function (doc) {
    var text = 'PSU CMS sample file\n\nTitle: ' + doc.title + '\nOriginal file name: ' + doc.fileName + '\n\n(This is mock content generated by the frontend prototype.)\n';
    return new Blob([text], { type: 'text/plain' });
  };

  /* ---------------- All Documents ---------------- */
  var rowsEl = document.getElementById('documentRows');
  if (rowsEl) {
    var forceEmpty = document.body.getAttribute('data-demo-empty') === '1';
    var search = A.$('#documentSearch'), cat = A.$('#filterCategory'), type = A.$('#filterType');
    var tableWrap = A.$('#documentTable'), footer = A.$('#documentFooter'), empty = A.$('#documentEmpty');
    var page = 1;
    var catId = Number(U.param('category')) || 0;

    function fillFilters() {
      CMS.ui.setOptions(cat, [{ value: '', label: 'All Categories' }].concat(PSU.db.all('categories').map(function (c) { return { value: String(c.id), label: c.name }; })), catId ? String(catId) : cat.value);
      CMS.ui.setOptions(type, [{ value: '', label: 'All File Types' }].concat(Object.keys(PSU.DOC_TYPES).map(function (k) { return { value: k, label: PSU.DOC_TYPES[k] }; })), type.value);
    }
    function render() {
      var q = search.value.trim().toLowerCase();
      var all = forceEmpty ? [] : PSU.db.all('documents');
      var list = all.filter(function (d) {
        if (cat.value && String(d.categoryId) !== cat.value) return false;
        if (type.value && d.ext !== type.value) return false;
        return !q || [d.title, d.fileName, d.description].join(' ').toLowerCase().indexOf(q) > -1;
      }).sort(function (a, b) { return a.createdAt < b.createdAt ? 1 : -1; });
      var filtered = !!(q || cat.value || type.value);
      var pg = U.paginate(list, page, PER_PAGE); page = pg.page;
      if (!pg.total) {
        tableWrap.hidden = true; footer.innerHTML = '';
        empty.innerHTML = A.emptyHtml('No documents available', 'Items you add will appear here.',
          '');
        return;
      }
      empty.innerHTML = ''; tableWrap.hidden = false;
      rowsEl.innerHTML = pg.items.map(function (d) {
        return '<tr><td>' + esc(d.title) + '</td><td>' + esc(d.ext.toUpperCase()) + '</td><td>' + esc(catName(d.categoryId)) + '</td><td>' + esc(U.fmtSize(d.size)) + '</td><td>' + esc(U.fmtDate(d.createdAt)) + '</td><td>' + esc(d.uploadedBy) + '</td>' +
          '<td><div class="cms-actions"><button type="button" class="cms-action" data-view="' + d.id + '">View</button><button type="button" class="cms-action" data-download="' + d.id + '">Download</button>' +
          '<a class="cms-action" href="upload-document.html?id=' + d.id + '">Edit</a><button type="button" class="cms-action cms-action-danger" data-delete="' + d.id + '">Delete</button></div></td></tr>';
      }).join('');
      footer.innerHTML = A.footerHtml(pg);
    }
    fillFilters();
    search.addEventListener('input', A.debounce(function () { page = 1; render(); }, 150));
    cat.addEventListener('change', function () { page = 1; render(); });
    type.addEventListener('change', function () { page = 1; render(); });
    A.$('#documentFilters').addEventListener('submit', function (e) { e.preventDefault(); page = 1; render(); });
    A.onPager(footer, function (n) { page = n; render(); });
    document.addEventListener('click', function (e) {
      if (e.target.closest('[data-clear]')) { search.value = ''; cat.value = ''; type.value = ''; CMS.ui.syncSelect(cat); CMS.ui.syncSelect(type); page = 1; render(); return; }
      var v = e.target.closest('[data-view]'), dl = e.target.closest('[data-download]'), del = e.target.closest('[data-delete]');
      var btn = v || dl || del;
      if (!btn) return;
      var d = PSU.db.get('documents', btn.getAttribute('data-view') || btn.getAttribute('data-download') || btn.getAttribute('data-delete'));
      if (!d) return;
      if (v) { window.open(URL.createObjectURL(PSUAdmin.sampleFile(d)), '_blank', 'noopener'); }
      else if (dl) {
        var a = document.createElement('a'); a.href = URL.createObjectURL(PSUAdmin.sampleFile(d)); a.download = d.fileName; document.body.appendChild(a); a.click(); a.remove();
        CMS.ui.toast('Download started (sample file).', 'info');
      } else {
        CMS.ui.confirmDelete({ text: 'Delete \u201C' + d.title + '\u201D? It will be removed from the document library.' }).then(function (ok) {
          if (!ok) return;
          PSU.db.remove('documents', d.id); CMS.ui.toast('Document deleted.', 'deleted'); render();
        });
      }
    });
    render();
  }

  /* ---------------- Document Categories ---------------- */
  var catRows = document.getElementById('categoryRows');
  if (catRows) {
    var cSearch = A.$('#categorySearch'), cTable = A.$('#categoryTable'), cFooter = A.$('#categoryFooter'), cEmpty = A.$('#categoryEmpty');
    var cPage = 1;
    var dialog = A.$('#categoryDialog'), modal = bootstrap.Modal.getOrCreateInstance(dialog);
    var cId = A.$('#categoryId'), cName = A.$('#categoryName'), cDesc = A.$('#categoryDescription'), cForm = A.$('#categoryForm');

    function renderCats() {
      var q = cSearch.value.trim().toLowerCase();
      var docs = PSU.db.all('documents');
      var list = PSU.db.all('categories').filter(function (c) { return !q || (c.name + ' ' + c.description).toLowerCase().indexOf(q) > -1; });
      var pg = U.paginate(list, cPage, PER_PAGE); cPage = pg.page;
      if (!pg.total) {
        cTable.hidden = true; cFooter.innerHTML = '';
        cEmpty.innerHTML = A.emptyHtml(q ? 'No categories match your search' : 'No categories available', q ? 'Try a different search.' : 'Items you add will appear here.');
        return;
      }
      cEmpty.innerHTML = ''; cTable.hidden = false;
      catRows.innerHTML = pg.items.map(function (c) {
        var n = docs.filter(function (d) { return d.categoryId === c.id; }).length;
        return '<tr><td>' + esc(c.name) + '</td><td>' + esc(c.description) + '</td><td>' + n + '</td><td><div class="cms-actions">' +
          '<a class="cms-action" href="all-documents.html?category=' + c.id + '">View</a>' +
          '<button type="button" class="cms-action" data-edit="' + c.id + '">Edit</button>' +
          '<button type="button" class="cms-action cms-action-danger" data-delete="' + c.id + '">Delete</button></div></td></tr>';
      }).join('');
      cFooter.innerHTML = A.footerHtml(pg);
    }
    function openDialog(c) {
      CMS.ui.clearErrors(cForm);
      cId.value = c ? c.id : ''; cName.value = c ? c.name : ''; cDesc.value = c ? c.description : '';
      A.$('#categoryTitle').textContent = c ? 'Edit Category' : 'Add Category';
      modal.show();
    }
    dialog.addEventListener('shown.bs.modal', function () { cName.focus(); });
    A.$('[data-category-add]').addEventListener('click', function () { openDialog(null); });
    cSearch.addEventListener('input', A.debounce(function () { cPage = 1; renderCats(); }, 150));
    A.$('#categoryFilters').addEventListener('submit', function (e) { e.preventDefault(); });
    A.onPager(cFooter, function (n) { cPage = n; renderCats(); });
    catRows.addEventListener('click', function (e) {
      var ed = e.target.closest('[data-edit]'), del = e.target.closest('[data-delete]');
      if (ed) { openDialog(PSU.db.get('categories', ed.getAttribute('data-edit'))); return; }
      if (!del) return;
      var c = PSU.db.get('categories', del.getAttribute('data-delete'));
      var n = PSU.db.all('documents').filter(function (d) { return d.categoryId === c.id; }).length;
      if (n > 0) { CMS.ui.toast('\u201C' + c.name + '\u201D still has ' + n + ' document' + (n === 1 ? '' : 's') + '. Move or delete them first.', 'error'); return; }
      CMS.ui.confirmDelete({ text: 'Delete the category \u201C' + c.name + '\u201D? This cannot be undone.' }).then(function (ok) {
        if (!ok) return; PSU.db.remove('categories', c.id); CMS.ui.toast('Category deleted.', 'deleted'); renderCats();
      });
    });
    cForm.addEventListener('submit', function (e) {
      e.preventDefault(); CMS.ui.clearErrors(cForm);
      var name = cName.value.trim(), id = Number(cId.value) || 0;
      if (!name) { CMS.ui.setError(cName, 'Category name is required.'); cName.focus(); return; }
      if (PSU.db.all('categories').some(function (c) { return c.id !== id && c.name.toLowerCase() === name.toLowerCase(); })) { CMS.ui.setError(cName, 'A category with this name already exists.'); cName.focus(); return; }
      var rec = id ? PSU.db.get('categories', id) : {};
      rec.name = name; rec.description = cDesc.value.trim();
      PSU.db.put('categories', rec);
      modal.hide(); CMS.ui.toast(id ? 'Category updated.' : 'Category added.', 'success'); renderCats();
    });
    renderCats();
  }

  /* ---------------- Upload / Edit Document ---------------- */
  var form = document.getElementById('documentForm');
  if (form) {
    var id = Number(U.param('id')) || 0, rec = id ? PSU.db.get('documents', id) : null;
    if (id && !rec) { A.go('That document no longer exists.', 'all-documents.html', 'error'); return; }
    var fileInput = A.$('#f_file'), nameOut = A.$('#f_file_name'), typeOut = A.$('#f_file_type'), title = A.$('#f_title');
    var picked = null;
    CMS.ui.setOptions(A.$('#f_category'), PSU.db.all('categories').map(function (c) { return { value: String(c.id), label: c.name }; }).concat([{ value: '', label: 'Uncategorized' }]), rec ? (rec.categoryId ? String(rec.categoryId) : '') : (PSU.db.all('categories')[0] ? String(PSU.db.all('categories')[0].id) : ''));
    if (rec) {
      title.value = rec.title; A.$('#f_description').value = rec.description || ''; nameOut.value = rec.fileName; typeOut.value = rec.ext.toUpperCase();
    }

    function onFile(file) {
      var msg = A.checkFile(file, PSU.DOC_TYPES);
      A.setFieldError('err_file', msg);
      if (msg) { fileInput.value = ''; picked = null; return; }
      picked = file; nameOut.value = file.name; typeOut.value = A.extOf(file.name).toUpperCase();
      if (!title.value.trim()) title.value = file.name.replace(/\.[^.]+$/, '').replace(/[_-]+/g, ' ');
    }
    A.dropzone(A.$('#documentDropzone'), fileInput, onFile);

    form.addEventListener('submit', function (e) {
      e.preventDefault(); CMS.ui.clearErrors(form); A.setFieldError('err_file', '');
      var bad = 0;
      if (!rec && !picked) { A.setFieldError('err_file', 'Select a file to upload.'); bad++; }
      if (!title.value.trim()) { CMS.ui.setError(title, 'Document title is required.'); bad++; }
      if (bad) { CMS.ui.toast('Please fix the highlighted fields.', 'error'); return; }
      var out = rec ? Object.assign({}, rec) : { downloads: 0, uploadedBy: 'Admin User', visibility: 'public', status: 'published' };
      out.title = title.value.trim(); out.description = A.$('#f_description').value.trim();
      out.categoryId = Number(A.$('#f_category').value) || 0;
      out.visibility = out.visibility || 'public'; out.status = out.status || 'published';
      if (picked) { out.fileName = picked.name; out.ext = A.extOf(picked.name); out.size = picked.size; }
      PSU.db.put('documents', out);
      A.go(rec ? 'Document updated.' : 'Document uploaded.', 'all-documents.html');
    });
  }
})();
