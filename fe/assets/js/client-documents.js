/* Public Document Library, staff-only dialog and Staff Login (mock data, no server). */
(function () {
  'use strict';
  var U = PSU.util, esc = U.esc;
  var PER_PAGE = 6;
  var DEMO = { email: 'staff@psu.edu.ph', password: 'staff1234' };

  function download(d) {
    var blob = new Blob(['PSU sample file\n\nTitle: ' + d.title + '\nFile: ' + d.fileName + '\n\n(Mock content generated by the frontend prototype.)\n'], { type: 'text/plain' });
    var a = document.createElement('a'); a.href = URL.createObjectURL(blob); a.download = d.fileName; document.body.appendChild(a); a.click(); a.remove();
    d.downloads = (d.downloads || 0) + 1; PSU.db.put('documents', d);
  }

  /* ---------------- library ---------------- */
  var list = document.getElementById('docList');
  if (list) {
    var search = document.getElementById('doc-search'), cat = document.getElementById('doc-category'), date = document.getElementById('doc-date');
    var chipsEl = document.getElementById('docChips'), empty = document.getElementById('docEmpty'), pager = document.getElementById('docPager');
    var page = 1;
    var cats = PSU.db.all('categories');
    function published() { return PSU.db.all('documents').filter(function (d) { return d.status === 'published'; }); }
    var usedCats = cats.filter(function (c) { return published().some(function (d) { return d.categoryId === c.id; }); });
    cat.innerHTML = '<option value="">All categories</option>' + usedCats.map(function (c) { return '<option value="' + c.id + '">' + esc(c.name) + '</option>'; }).join('');
    function chips() {
      chipsEl.innerHTML = '<li><button type="button" class="chip' + (cat.value === '' ? ' is-active' : '') + '" data-cat="">All</button></li>' +
        usedCats.map(function (c) { return '<li><button type="button" class="chip' + (String(c.id) === cat.value ? ' is-active' : '') + '" data-cat="' + c.id + '">' + esc(c.name) + '</button></li>'; }).join('');
    }
    function render() {
      var q = search.value.trim().toLowerCase();
      var days = { '7d': 7, '30d': 30, '1y': 365 }[date.value] || 0;
      var cutoff = days ? Date.now() - days * 86400000 : 0;
      var items = published().filter(function (d) {
        if (cat.value && String(d.categoryId) !== cat.value) return false;
        if (cutoff && new Date(d.createdAt).getTime() < cutoff) return false;
        return !q || d.title.toLowerCase().indexOf(q) > -1;
      }).sort(function (a, b) { return a.createdAt < b.createdAt ? 1 : -1; });
      var filtered = !!(q || cat.value || date.value);
      var pg = U.paginate(items, page, PER_PAGE); page = pg.page;
      chips();
      if (!pg.total) {
        list.innerHTML = ''; pager.innerHTML = ''; empty.hidden = false;
        empty.innerHTML = '<p class="listing-empty__title">' + (filtered ? 'No documents match your search' : 'No documents available yet') + '</p><p>' + (filtered ? 'Try a different title, category, or date range.' : 'Official documents will be posted here.') + '</p>' + (filtered ? '<button class="btn btn--outline" type="button" data-clear>Clear filters</button>' : '');
        return;
      }
      empty.hidden = true;
      list.innerHTML = pg.items.map(function (d) {
        var c = PSU.db.get('categories', d.categoryId);
        var meta = [c ? c.name : 'Uncategorized', d.ext.toUpperCase(), U.fmtSize(d.size), U.fmtDate(d.createdAt), d.visibility === 'staff' ? 'Staff only' : (d.downloads || 0).toLocaleString('en-US') + ' download' + (d.downloads === 1 ? '' : 's')].join(' \u00B7 ');
        var action = '<button type="button" class="btn btn--outline doc-row__action" data-download="' + d.id + '" aria-label="Download ' + esc(d.title) + '">Download</button>';
        return '<li class="doc-row"><span class="doc-row__icon" aria-hidden="true">' + esc(d.ext === 'docx' ? 'DOC' : d.ext.toUpperCase()) + '</span><div class="doc-row__info"><h2 class="doc-row__title">' + esc(d.title) + '</h2><p class="doc-row__meta">' + esc(meta) + '</p></div>' + action + '</li>';
      }).join('');
      pager.innerHTML = U.pagerHtml(pg, 'pager__btn', 'pager');
    }
    search.addEventListener('input', function () { page = 1; render(); });
    cat.addEventListener('change', function () { page = 1; render(); });
    date.addEventListener('change', function () { page = 1; render(); });
    document.getElementById('docForm').addEventListener('submit', function (e) { e.preventDefault(); page = 1; render(); });
    chipsEl.addEventListener('click', function (e) { var b = e.target.closest('[data-cat]'); if (b) { cat.value = b.getAttribute('data-cat'); page = 1; render(); } });
    pager.addEventListener('click', function (e) { var b = e.target.closest('[data-page]'); if (b && !b.disabled) { page = Number(b.getAttribute('data-page')); render(); } });
    empty.addEventListener('click', function (e) { if (e.target.closest('[data-clear]')) { search.value = ''; cat.value = ''; date.value = ''; page = 1; render(); } });

    list.addEventListener('click', function (e) {
      var dl = e.target.closest('[data-download]');
      if (dl) { var doc = PSU.db.get('documents', dl.getAttribute('data-download')); if (doc) { download(doc); render(); } }
    });
    render();
  }

  /* ---------------- staff login ---------------- */
  var login = document.getElementById('staffLoginForm');
  if (login) {
    var alertEl = document.getElementById('loginAlert');
    login.addEventListener('submit', function (e) {
      e.preventDefault();
      var email = document.getElementById('staff-email').value.trim().toLowerCase(), pw = document.getElementById('staff-password').value;
      if (!email || !pw) { alertEl.textContent = 'Enter your email and password.'; alertEl.hidden = false; return; }
      if (email === DEMO.email && pw === DEMO.password) {
        try { sessionStorage.setItem('psu.staff', '1'); } catch (err) {}
        location.href = 'documents.html';
      } else { alertEl.textContent = 'Email or password is incorrect.'; alertEl.hidden = false; document.getElementById('staff-password').value = ''; }
    });
  }
})();
